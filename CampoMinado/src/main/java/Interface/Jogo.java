boolean [][] bombas  = new boolean [10][10];

//MATRIZ PARA OS CAMPOS QUE FOREM ABERTOS
 boolean [][] abertos = new boolean [10] [10];
 
 int quantidadeBombas = 15;
 
 boolean jogoEncerrado= false;
 
 int quantidadeDeCasasAbertas=0;
 
            
